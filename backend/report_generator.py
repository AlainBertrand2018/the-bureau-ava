    @staticmethod
    def _sharpen_text(text: str) -> str:
        """
        Premium Sharpening Unit:
        1. Removes redundant sentences.
        2. Filters out AI meta-talk (explainers).
        3. Cleans punctuation artifacts.
        """
        if not text or not isinstance(text, str):
            return text
            
        # Segment into sentences (basic regex for . ? !)
        sentences = re.split(r'(?<=[.!?])\s+', text.strip())
        
        unique_sentences = []
        seen_normalized = set()
        
        # Meta-talk filter patterns
        meta_patterns = [
            r'^considering the.*',
            r'^it\'s best to.*',
            r'^example:.*',
            r'^this question.*',
            r'^the goal of.*',
            r'^note:.*'
        ]
        
        for s in sentences:
            # Skip if it's meta-talk
            if any(re.match(p, s, re.IGNORECASE) for p in meta_patterns):
                continue
                
            # Deduplicate (fuzzy normalized)
            norm = "".join(filter(str.isalnum, s.lower()))
            if norm and norm not in seen_normalized:
                unique_sentences.append(s)
                seen_normalized.add(norm)
                
        sharpened = " ".join(unique_sentences)
        # Final cleanup for multiple periods or whitespace
        sharpened = re.sub(r'\.+', '.', sharpened)
        return sharpened.strip()

    @staticmethod
    def _clean_question(q_text: str) -> str:
        """Removes the parenthetical options from the question text, even if not at the absolute end."""
        # Find all parenthetical content that looks like a response scale
        # We look for common markers of options rather than just trailing position
        pattern = r'\s*\([^)]*?(?:=|/|;|times|satisfied|agree|disagree|never|often|yes|no|always|maybe)[^)]*\)'
        cleaned = re.sub(pattern, '', q_text.strip(), flags=re.IGNORECASE)
        # Also strip any trailing conversational prompts AI often adds
        cleaned = re.sub(r'\s+e\.g\..*$', '', cleaned, flags=re.IGNORECASE)
        # Clean up any trailing punctuation or extra whitespace
        cleaned = re.sub(r'\s+([.?!])', r'\1', cleaned)
        return cleaned

    @staticmethod
    def _parse_field_options(q_text: str) -> List[str]:
        """
        Extracts options from survey questions. 
        Prioritizes logical delimiters (/, ;) to avoid breaking numerical values with commas.
        """
        import re
        # Find any set of parentheses that contains common option markers
        matches = re.findall(r'\(([^)]+)\)', q_text)
        if not matches:
            return []
            
        # REJECT criteria: If the parenthesis is too long (likely an explanation, not options)
        # or doesn't contain separators.
        valid_matches = []
        for m in matches:
            if len(m) > 150: continue # Likely meta-talk
            valid_matches.append(m)
            
        if not valid_matches: return []
        
        # We usually want the one that looks most like a scale
        # (contains separators or common scale words)
        best_match = ""
        max_markers = -1
        
        markers = ['/', ';', '=', 'yes', 'no', 'agree', 'satisfied', 'never']
        for m in valid_matches:
            score = sum(1 for marker in markers if marker in m.lower())
            if score > max_markers:
                max_markers = score
                best_match = m
        
        if max_markers == -1:
            # Fallback to the last match if none look like scales
            best_match = matches[-1]

        # Prioritize delimiters: / and ; are safer than , (which breaks numbers)
        for sep in [' / ', '/', ' ; ', ';']:
            if sep in best_match:
                return [o.strip() for o in best_match.split(sep) if o.strip()]
        
        # If no strong delimiters, check comma but verify it's not a number
        if ',' in best_match:
            # Simple heuristic: if most comma-separated parts have letters, it's a list, not thousands
            parts = [o.strip() for o in best_match.split(',') if o.strip()]
            if any(re.search(r'[a-zA-Z]', p) for p in parts):
                return parts
                
        # Handle dash-separated ranges
        if " - " in best_match:
            return [o.strip() for o in best_match.split(" - ")]
            
        return [best_match.strip()]

